CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50) NOT NULL UNIQUE,
    EMAIL VARCHAR2(100) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(255) NOT NULL,
    FULL_NAME VARCHAR2(100) NOT NULL,
    PHONE_NO VARCHAR2(15) NOT NULL,
    ROLE VARCHAR2(10) CHECK (ROLE IN ('STUDENT', 'ADMIN')) NOT NULL,
    ROLL_NO VARCHAR2(30) UNIQUE,
    COURSE VARCHAR2(50),
    DOB DATE NOT NULL,
    GENDER VARCHAR2(10) CHECK (GENDER IN ('Male', 'Female', 'Other')) NOT NULL,
    TERMS_ACCEPTED CHAR(1) DEFAULT 'Y' CHECK (TERMS_ACCEPTED IN ('Y', 'N')) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
-- =========================================
-- 2. CREATE PROJECTS TABLE
-- =========================================
CREATE TABLE PROJECTS (
    PROJECT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STUDENT_ID NUMBER NOT NULL,
    TITLE VARCHAR2(200) NOT NULL,
    DESCRIPTION VARCHAR2(2000) NOT NULL,
    TECH_STACK VARCHAR2(255),
    PROJECT_LINK VARCHAR2(500),
    DOCUMENT_PATH VARCHAR2(500),
    STATUS VARCHAR2(20) DEFAULT 'PENDING' CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED')),
    SUBMITTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PROJECT_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);
-- =========================================
-- 3. CREATE PROJECT_REVIEWS TABLE
-- =========================================
CREATE TABLE PROJECT_REVIEWS (
    REVIEW_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROJECT_ID NUMBER NOT NULL UNIQUE,
    ADMIN_ID NUMBER NOT NULL,
    RATING NUMBER(2, 1) CHECK (RATING BETWEEN 1.0 AND 5.0),
    FEEDBACK VARCHAR2(1000),
    REVIEWED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_REVIEW_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES PROJECTS(PROJECT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_REVIEW_ADMIN FOREIGN KEY (ADMIN_ID) REFERENCES USERS(USER_ID)
);